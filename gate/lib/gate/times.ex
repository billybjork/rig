defmodule Gate.Times do
  @moduledoc """
  `gate times`: rewrites the project's `weights` file, the time each test
  file took in the newest split gate whose every suite part (`test-*`) was
  green, which the project's `gate_parts` deals the suite's partitions by.
  Each suite part's log ends with its formatter's lines, one per test file:
  `gate-time: <file> <async ms> <sync ms>`. Commit the file on its own when
  the suite parts' times drift apart.
  """

  alias Gate.Check

  def main(config, []) do
    weights = config.weights || raise Gate.Error, ".gate.json names no weights file"

    parts =
      config
      |> Check.parts("check")
      |> Enum.count(fn {name, _} -> String.starts_with?(name, "test-") end)

    logs = File.ls!(config.logs)
    pool = Enum.map_join(config.pool, "|", &Regex.escape/1)
    pattern = ~r/\A(#{pool})-(\d{8}-\d{6}-[0-9a-f]{8})-(test-\d+)\.log\z/

    found =
      for file <- logs,
          [_, _sprite, run, part] <- [Regex.run(pattern, file)],
          do: {run, part, file}

    green? = fn file ->
      text = File.read!(Path.join(config.logs, file))
      text =~ ~r/^gate-time: /m and Gate.Sprite.last_line(text) == "sprite-gate: exit 0"
    end

    run =
      found
      |> Enum.group_by(&elem(&1, 0))
      |> Enum.sort(:desc)
      |> Enum.find_value(fn {run, logs} ->
        greens = logs |> Enum.filter(&green?.(elem(&1, 2))) |> Enum.uniq_by(&elem(&1, 1))
        if length(greens) == parts, do: {run, greens}
      end)

    {run, greens} =
      run ||
        raise Gate.Error,
              "no split gate with #{parts} green suite parts and gate-time lines in #{config.logs}"

    times =
      for {_, _, file} <- greens,
          line <- config.logs |> Path.join(file) |> File.read!() |> String.split(["\n", "\r"]),
          ["gate-time:", test, async, sync] <- [String.split(line)],
          into: %{},
          do: {test, {String.to_integer(async), String.to_integer(sync)}}

    # Credo reads the file: numbers past 9999 take underscores.
    ms = &String.replace(Integer.to_string(&1), ~r/\B(?=(\d{3})+$)/, "_")

    body =
      Enum.map_join(Enum.sort(times), ",\n", fn {file, {async, sync}} ->
        "  #{inspect(file)} => {#{ms.(async)}, #{ms.(sync)}}"
      end)

    path = Path.join(config.top, weights)

    File.write!(path, """
    # Each test file's wall time in a green split gate, {async ms, sync ms}:
    # the weights mix.exs gate_parts deals the suite's partitions by.
    # Generated by `gate times` (~/dev/rig/gate); do not edit.
    %{
    #{body}
    }
    """)

    # Long file names wrap, so the file takes the formatter's layout.
    System.cmd("mix", ["format", weights], cd: config.top)
    IO.puts(:stderr, "gate-times: #{map_size(times)} files from run #{run}")
    0
  end
end
